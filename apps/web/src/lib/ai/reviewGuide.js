/** 可供 AI 說明「哪些獎學金有專屬檢核重點」 */
export const REVIEW_GUIDE_NAMES = SCHOLARSHIP_GUIDES.map(g => g.name);

/**
 * 依公告標題／內容比對出該獎學金的專屬檢核重點。
 * @param {string} haystack 用來比對的文字（公告標題 + 內容摘要 + 使用者提問）
 * @param {number} limit 最多注入幾份（控制系統提示長度）
 */
export function matchScholarshipGuides(haystack, limit = 2) {
    const text = String(haystack || '');
    if (!text.trim()) return [];
    return SCHOLARSHIP_GUIDES.filter(g => g.keywords.some(k => text.includes(k))).slice(0, limit);
}

/**
 * 組出檢核模式要注入系統提示的完整區塊。
 * @param {Object} options
 * @param {string} [options.announcementTitle] 使用者以「@」指定的公告標題
 * @param {string} [options.announcementContent] 該公告的知識庫內容（作為檢核基準）
 * @param {string} [options.userText] 使用者本輪提問（沒指定公告時也能命中獎學金名稱）
 */
export function buildReviewContext({ announcementTitle = '', announcementContent = '', userText = '' } = {}) {
    const parts = [REVIEW_BASE_GUIDE];

    const matched = matchScholarshipGuides(`${announcementTitle}\n${announcementContent.slice(0, 1200)}\n${userText}`);
    if (matched.length > 0) {
        parts.push(
            matched.map(g => `### 【${g.name}】專屬檢核重點\n${g.content}`).join('\n\n'),
        );
    }

    if (announcementTitle) {
        parts.push(`### 本次檢核基準公告：「${announcementTitle}」
以下方公告內容的申請資格、評選重點與應繳文件為準，對使用者提供的文件逐點檢核；公告與上方通則衝突時，以公告為準。

${announcementContent.slice(0, 4000)}`);
    } else {
        parts.push(`### 尚未指定獎學金
使用者還沒用「@」指定要申請哪一則公告。可先依上方通則檢核，並提醒對方指定公告後能對照該獎學金的資格與評選重點；平台目前另有這些獎學金的專屬檢核重點可用：${REVIEW_GUIDE_NAMES.join('、')}。`);
    }

    return parts.join('\n\n');
}
